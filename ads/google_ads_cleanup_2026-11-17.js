/**
 * Чистка по отчёту 10–16 ноября. Делает ровно три вещи:
 *  1. Ставит на паузу три ключа, которые съели $47 из $65 нецелевым трафиком.
 *  2. Добавляет минус-слова по реальным поисковым запросам недели.
 *  3. Ничего больше: группы, объявления, гео, ставки — не трогает.
 * Партнёрскую сеть выключить руками: Настройки кампании → Сети.
 */

var CAMPAIGN_NAME = 'Search RU | v-dostatke';

var PAUSE_KEYWORDS = ['способ заработка', 'онлайн сессия с психологом', 'уверенность в себе'];

var NEGATIVES = [
  // подработка / заработок
  'заработок', 'заработать', 'зарабатывать', 'заработка', 'в интернете', 'без вложений', 'с телефона', 'на телефоне',
  'с выводом', 'на карту', 'опросы', 'за опросы', 'онлифанс', 'onlyfans', 'ютуб', 'youtube', 'монетизация', 'монетизировать',
  'инстаграм', 'pinterest', 'shutterstock', 'фриланс', 'перепечатка', 'написание текстов', 'тендер', 'игре', 'игры', 'игра',
  'p2p', 'admitad', 'appen', 'clickworker', 'toluna', 'work zilla', 'test io', 'за 5 минут', 'срочно нужны деньги',
  'в 13 лет', 'подростка', 'подросток', 'идеи для заработка', 'чем заняться', 'удаленно', 'на дому', 'дома',
  // бесплатный / дешёвый психолог, чужие бренды
  'бесплатные', 'бесплатный', 'бесплатная', 'дешево', 'дёшево', 'чат', 'виртуальный', 'сайт психолога', 'психолог сайт',
  'профи', 'profi', 'mindly', 'степанова', 'кунах', 'сексолог', 'спортивный', 'психотерапия',
  // клиника / диагнозы
  'расстройство', 'прл', 'кптср', 'пограничное', 'депрессии', 'депрессия', 'тревожность', 'тревогу', 'руминации',
  'паническ', 'психиатр',
  // отношения, общее настроение
  'отношениях', 'о человеке', 'о прошлом', 'настроение', 'полюбить себя', 'позитивное мышление', 'силу воли',
  'экзистенциальный', 'как жить дальше', 'позиции жертвы', 'заплачу за общение', 'беспокоиться и начать жить',
  // эзотерика
  'привлечь деньги'
];

function main() {
  var it = AdsApp.campaigns().get(), campaign = null;
  while (it.hasNext()) { var c = it.next(); if (c.getName().replace(/[«»]/g, '').trim() === CAMPAIGN_NAME) campaign = c; }
  if (!campaign) { Logger.log('Кампания не найдена'); return; }

  var paused = 0;
  var kws = campaign.keywords().get();
  while (kws.hasNext()) {
    var k = kws.next();
    var text = k.getText().replace(/^["\[\+]|["\]]$/g, '').trim().toLowerCase();
    if (PAUSE_KEYWORDS.indexOf(text) !== -1 && k.isEnabled()) { k.pause(); paused++; Logger.log('Пауза: ' + k.getText()); }
  }

  var existing = {};
  var ne = campaign.negativeKeywords().get();
  while (ne.hasNext()) existing[ne.next().getText().replace(/^"|"$/g, '').toLowerCase()] = true;
  var added = 0;
  NEGATIVES.forEach(function (n) {
    if (existing[n.toLowerCase()]) return;
    try { campaign.createNegativeKeyword('"' + n + '"'); added++; } catch (e) { Logger.log('Минус не добавлен: ' + n + ' — ' + e); }
  });

  Logger.log('ИТОГ: ключей на паузе ' + paused + ', минус-слов добавлено ' + added);
  Logger.log('Руками: Настройки кампании → Сети → снять «Поисковые партнёры».');
}
